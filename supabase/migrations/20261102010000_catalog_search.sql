create extension if not exists unaccent;

-- unaccent() is not immutable: wrapper so it can be used in a generated column / index.
create or replace function public.f_unaccent(text) returns text
language sql immutable parallel safe strict
set search_path = public, extensions
as $$ select unaccent('unaccent', $1) $$;

alter table public.foods
  add column name_norm text generated always as (lower(public.f_unaccent(name_fr))) stored;
create index foods_name_norm_trgm on public.foods using gin (name_norm gin_trgm_ops);

alter table public.dishes
  add column name_norm text generated always as (lower(public.f_unaccent(name_fr))) stored;

-- Common short forms typed by users (reviewed, editorial). term and expansion are normalised.
create table public.search_synonyms (
  term       text primary key,
  expansion  text not null
);
alter table public.search_synonyms enable row level security;
create policy "lecture publique" on public.search_synonyms for select using (true);
grant select on public.search_synonyms to anon, authenticated;
grant all on public.search_synonyms to service_role;

